"""Export the data behind the three concept animations to <project>/assets/data.js.

Same simulations and seeds as the slides (slides/figures.py) and the notebooks,
so every point and line in the videos matches the static figures.

    uv run python animations/make_data.py
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.formula.api as smf

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "slides"))
from figures import TRUE, repeat_study, simulate_reading  # noqa: E402


def r(x, k=3):
    return np.round(np.asarray(x, dtype=float), k).tolist()


def write(project, data):
    out = HERE / project / "assets" / "data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// Generated by animations/make_data.py: do not edit by hand.\n"
        f"window.ANIM_DATA = {json.dumps(data, separators=(',', ':'))};\n"
    )
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size / 1024:.0f} kB)")


def where_data_come_from():
    df = simulate_reading()
    fit = smf.ols("time ~ words", df).fit()
    write(
        "01_where_data_come_from",
        {
            "x": r(df["words"], 2),
            "y": r(df["time"], 2),
            "true": TRUE,
            "ols": {
                "intercept": round(float(fit.params["Intercept"]), 4),
                "slope": round(float(fit.params["words"]), 4),
            },
            "bells": [2, 5, 8, 11],
        },
    )


def repeat_the_study(n_studies=200, n_with_points=40):
    # Same seed sequence as the sampling-distribution figure on the slides:
    # each study keeps our 40 texts and draws new reading times.
    rng = np.random.default_rng(7)
    sims = [repeat_study(seed=int(rng.integers(1e9))) for _ in range(n_studies)]
    # The Normal model occasionally simulates a (slightly) negative reading time.
    # Studies are exchangeable, so show the points of studies without one first;
    # the histogram still uses all 200 slopes.
    order = sorted(range(n_studies), key=lambda k: bool((sims[k]["time"] < 0).any()))
    studies = []
    for rank, k in enumerate(order):
        d = sims[k]
        slope, intercept = np.polyfit(d["words"], d["time"], 1)
        s = {"a": round(float(intercept), 4), "b": round(float(slope), 4)}
        if rank < n_with_points:
            assert (d["time"] >= 0).all()
            s["x"] = r(d["words"], 2)
            s["y"] = r(d["time"], 2)
        studies.append(s)
    slopes = np.array([s["b"] for s in studies])
    write(
        "02_repeat_the_study",
        {"true": TRUE, "studies": studies, "sd": round(float(slopes.std()), 4)},
    )


def holding_constant():
    kid = pd.read_csv(ROOT / "data" / "kidiq.csv")
    fit = smf.ols("kid_score ~ mom_hs + mom_iq", kid).fit()
    rng = np.random.default_rng(3)
    write(
        "03_holding_constant",
        {
            "hs": kid["mom_hs"].astype(int).tolist(),
            "iq": r(kid["mom_iq"], 2),
            "score": kid["kid_score"].astype(int).tolist(),
            "jitter": r(rng.uniform(-1, 1, len(kid)), 3),  # column jitter, -1..1
            "delay": r(rng.uniform(0, 1, len(kid)), 3),  # stagger, 0..1
            "mean_score": r(kid.groupby("mom_hs")["kid_score"].mean(), 2),
            "mean_iq": r(kid.groupby("mom_hs")["mom_iq"].mean(), 2),
            "fit": {
                "intercept": round(float(fit.params["Intercept"]), 4),
                "b_hs": round(float(fit.params["mom_hs"]), 4),
                "b_iq": round(float(fit.params["mom_iq"]), 4),
            },
        },
    )


if __name__ == "__main__":
    where_data_come_from()
    repeat_the_study()
    holding_constant()
